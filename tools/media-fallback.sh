#!/usr/bin/env bash
# Serve missing uploads from production: writes a per-project nginx template
# (.devilbox/nginx.yml) that 302-redirects any /wp-content/uploads/* file that
# does not exist locally to the same path on the production site, and also
# accepts *.<project>.<tld> for multisite networks.
#
# usage: tools/media-fallback.sh <project> <https://production.example.com> [--subdir-multisite]
#        tools/media-fallback.sh <project> --off
#        tools/media-fallback.sh <project> --status      -> MEDIA|<project>|<url or off>
#
# The web server is restarted afterwards so the new vhost config loads.
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

P="${1:?usage: media-fallback.sh <project> <prod-url|--off|--status>}"; ARG="${2:-}"; SUBDIR=0
[ "${3:-}" = "--subdir-multisite" ] && SUBDIR=1
D="$WWW/$P"; [ -d "$D" ] || die "project $P not found"
CFG="$D/.devilbox/nginx.yml"

case "$ARG" in
  --status)
    if [ -f "$CFG" ] && grep -q "prod_uploads" "$CFG"; then echo "MEDIA|$P|$(grep -oE 'return 302 https?://[^$]+' "$CFG" | head -1 | sed -E 's/return 302 //')"
    else echo "MEDIA|$P|off"; fi; exit 0;;
  --off)
    if [ -f "$CFG" ] && grep -q "Devilbox-Boost per-project nginx template" "$CFG"; then rm -f "$CFG"; rmdir "$D/.devilbox" 2>/dev/null || true; fi
    compose restart httpd >/dev/null 2>&1 && ok "media fallback off for $P (httpd restarted)"; echo "MEDIA|$P|off"; exit 0;;
  http://*|https://*) PROD="${ARG%/}";;
  *) die "second argument must be a production URL, --off or --status";;
esac

TEMPLATE=$(compose exec -T httpd cat /etc/vhost-gen/templates/nginx.yml </dev/null) || die "could not read the nginx template from the httpd container"
echo "$TEMPLATE" | grep -q 'server_name  __VHOST_NAME__;' || die "unexpected template format"

SUBDIR_RULES=""
if [ "$SUBDIR" = 1 ]; then
SUBDIR_RULES='    # Subdirectory multisite: route /<site>/wp-admin and /<site>/*.php to the root install
    if (!-e $request_filename) {
        rewrite /wp-admin$ $scheme://$host$uri/ permanent;
        rewrite ^(/[^/]+)?(/wp-.*) $2 last;
        rewrite ^(/[^/]+)?(/.*\.php) $2 last;
    }
'
fi
PROD_HOST=$(echo "$PROD" | sed -E 's#^https?://##')
mkdir -p "$D/.devilbox"
{
  echo "---"
  echo "# Devilbox-Boost per-project nginx template ($P), generated by tools/media-fallback.sh."
  echo "# server_name accepts *.$P.$TLD; missing /wp-content/uploads/* files redirect to $PROD."
  echo "$TEMPLATE" | sed '1{/^---$/d;}' \
    | sed 's/server_name  __VHOST_NAME__;/server_name  __VHOST_NAME__ *.__VHOST_NAME__;/' \
    | awk -v rules="$SUBDIR_RULES" -v prod="$PROD" '
      /^    location \/ \{$/ && !done {
        printf "%s", rules
        print; getline; print; getline; print   # location / { try_files ...; }
        print "    # Uploads are not in git: fall back to the production copy for anything missing locally"
        print "    location ~* ^/wp-content/uploads/ {"
        print "        try_files $uri @prod_uploads;"
        print "    }"
        print "    location @prod_uploads {"
        print "        return 302 " prod "$request_uri;"
        print "    }"
        done=1; next }
      { print }'
} > "$CFG"
grep -q "return 302 $PROD" "$CFG" || die "template generation failed"
[ -d "$D/.git" ] && { mkdir -p "$D/.git/info"; grep -qx ".devilbox/" "$D/.git/info/exclude" 2>/dev/null || echo ".devilbox/" >> "$D/.git/info/exclude"; }
compose restart httpd >/dev/null 2>&1 || warn "httpd restart failed; restart it to load the vhost"
ok "media fallback for $P → $PROD_HOST (httpd restarted)"
echo "MEDIA|$P|$PROD"
